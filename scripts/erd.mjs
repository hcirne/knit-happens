// Generates docs/architecture/erd.md (a Mermaid entity-relationship diagram)
// from prisma/schema.prisma.   Run it with:  npm run docs:erd

import fs from "node:fs";
import path from "node:path";
import { parseSchema } from "./lib/prisma-schema.mjs";

const root = path.resolve(import.meta.dirname, "..");
const { models, enums } = parseSchema(path.join(root, "prisma/schema.prisma"));

const modelNames = models.map((m) => m.name);
const enumNames = enums.map((e) => e.name);

const diagram = ["erDiagram"];
const relationships = [];

for (const model of models) {
  // Names of fields that are foreign keys (listed in some @relation(fields: ...)).
  const foreignKeys = new Set();
  for (const field of model.fields) {
    if (field.relation) field.relation.fields.forEach((f) => foreignKeys.add(f));
  }

  diagram.push(`    ${model.name} {`);
  for (const field of model.fields) {
    // Fields whose type is another model (author User, projects Project[]) are
    // relationships, not columns, so they are not listed as attributes.
    if (modelNames.includes(field.type)) continue;

    const keys = [];
    if (field.isId) keys.push("PK");
    if (foreignKeys.has(field.name)) keys.push("FK");
    if (field.isUnique) keys.push("UK");

    // Mermaid allows several markers separated by commas: "PK, FK".
    const marker = keys.length > 0 ? ` ${keys.join(", ")}` : "";
    diagram.push(`        ${field.type} ${field.name}${marker}`);

    // A dashed line links a model to the enum it uses.
    if (enumNames.includes(field.type)) {
      relationships.push(`    ${model.name} }o..|| ${field.type} : "${field.name}"`);
    }
  }
  diagram.push("    }");

  // One relationship per @relation(fields: ...), drawn from parent to child.
  for (const field of model.fields) {
    if (!field.relation || field.relation.fields.length === 0) continue;
    const fkField = model.fields.find((f) => f.name === field.relation.fields[0]);
    const parentSide = fkField && fkField.optional ? "|o" : "||";
    const onDelete = field.relation.onDelete ? ` (${field.relation.onDelete})` : "";
    relationships.push(`    ${field.type} ${parentSide}--o{ ${model.name} : "${field.name}${onDelete}"`);
  }
}

for (const e of enums) {
  diagram.push(`    ${e.name} {`);
  for (const value of e.values) diagram.push(`        string ${value}`);
  diagram.push("    }");
}

diagram.push(...relationships);

const output = [
  "# Entity-relationship diagram",
  "",
  "This file is auto-generated by `npm run docs:erd` from `prisma/schema.prisma`. Do not edit it by hand.",
  "",
  "```mermaid",
  ...diagram,
  "```",
  "",
].join("\n");

const outFile = path.join(root, "docs/architecture/erd.md");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output);
console.log("Wrote docs/architecture/erd.md");
